function assertTables() {
  if (AMP_PRIOR.a !== TABLE_A || AMP_PRIOR.b !== TABLE_B || AMP_PRIOR.t_min !== TABLE_T_MIN) {
    throw new Error(
      `prior.js: the amplitude tables were computed for a=${TABLE_A}, b=${TABLE_B}, ` +
        `t_min=${TABLE_T_MIN}, but config.AMP_PRIOR is ${JSON.stringify(AMP_PRIOR)}. Recompute them.`
    );
  }
}

/** Linear interpolation of a CDF table on a uniform grid over [x0, x1]. */
function tableCdf(tab, x0, x1, x) {
  if (x <= x0) return 0;
  if (x >= x1) return 1;
  const pos = ((x - x0) / (x1 - x0)) * (tab.length - 1);
  const k = Math.floor(pos);
  const t = pos - k;
  return tab[k] * (1 - t) + tab[k + 1] * t;
}

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

/**
 * The prior CDF of one parameter at x. RAISES for a parameter with no prior.
 * @param {string} key registered parameter
 * @param {string} ev site event key
 * @param {number} x
 * @returns {number}
 */
export function priorCdf(key, ev, x) {
  getParam(key);
  switch (key) {
    case "f":
    case "gamma": {
      const [lo, hi] = priorBox(key, ev);
      return clamp01((x - lo) / (hi - lo));
    }
    case "tau": {
      // gamma uniform on [g0, g1]  =>  P(tau <= x) = P(gamma >= 1/x).
      const [g0, g1] = priorBox("gamma", ev);
      if (!(x > 0)) return 0;
      return clamp01((g1 - 1 / x) / (g1 - g0));
    }
    case "A":
      assertTables();
      return tableCdf(CDF_S, 0, S_MAX, x * Math.sqrt(TABLE_T_MIN));
    case "epsilon":
      assertTables();
      if (x <= -1) return 0;
      if (x >= 1) return 1;
      return tableCdf(CDF_U, -Math.PI / 2, Math.PI / 2, Math.asin(x));
    case "phi":
      return clamp01(x / (2 * Math.PI));
    case "theta":
      return clamp01(x / Math.PI);
    default:
      throw new Error(`prior.priorCdf: no prior declared for "${key}"`);
  }
}

/**
 * The support of the prior of one parameter. `A` has no upper bound.
 * @param {string} key @param {string} ev
 * @returns {number[]} [lo, hi]
 */
export function priorSupport(key, ev) {
  getParam(key);
  switch (key) {
    case "f":
    case "gamma":
      return priorBox(key, ev);
    case "tau": {
      const g = priorBox("gamma", ev);
      return [1 / g[1], 1 / g[0]];
    }
    case "A":
      return [0, Infinity];
    case "epsilon":
      return [-1, 1];
    case "phi":
      return [0, 2 * Math.PI];
    case "theta":
      return [0, Math.PI];
    default:
      throw new Error(`prior.priorSupport: no prior declared for "${key}"`);
  }
}

/**
 * Bin-averaged prior density over nb equal bins of [lo, hi].
 * @returns {Float64Array} length nb, probability per unit of the parameter
 */
export function priorBinDensity(key, ev, lo, hi, nb) {
  const out = new Float64Array(nb);
  const w = (hi - lo) / nb;
  let prev = priorCdf(key, ev, lo);
  for (let k = 0; k < nb; k++) {
    const next = priorCdf(key, ev, lo + (k + 1) * w);
    out[k] = (next - prev) / w;
    prev = next;
  }
  return out;
}
