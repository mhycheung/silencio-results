/**
 * prior.js — the per-mode PRIOR of every corner-plot parameter, for the prior
 * overlay (user request 2026-09-18: "a toggle for plotting the prior in grey
 * dotted lines ... the prior bounds in 2D, and the 1D marginal prior").
 *
 * THE PRIOR (one mode; every mode has the same one):
 *   - f uniform on the event's prior box, gamma = 1/tau uniform on its box
 *     (config.priorBox). So tau has density proportional to 1/tau^2.
 *   - Amplitude and polarisation (a = b = 3/2 with the auxiliary floor t_min,
 *     config.AMP_PRIOR): density in (A, eps) proportional to
 *     (1 - eps^2)^(-1/2) Q(3/4, t_min A_R^2) Q(3/4, t_min A_L^2), with
 *     A_R = A (1 - eps)/2, A_L = A (1 + eps)/2 and Q the regularised upper
 *     incomplete gamma function. Flat in A up to a taper near 1e-18; eps close
 *     to the arcsine law.
 *   - The phases are uniform, so phi is uniform on [0, 2 pi] and theta on [0, pi].
 *
 * The A and eps marginals have no closed form. They are TABULATED as CDFs with
 * scipy (script prior_tables_2026-09-18.py): CDF_S on a uniform grid of
 * s = A sqrt(t_min) in [0, 12.0], and CDF_U on a uniform grid of u = asin(eps)
 * in [-pi/2, pi/2]. An independent importance-weighted Monte Carlo (2e6 draws)
 * agreed to 2.4e-3 (A) and 2.1e-3 (eps) in CDF; with the floor removed the A CDF
 * disagreed by 0.83 (negative control).
 *
 * THE LABEL CAVEAT. This is the prior of one SAMPLER SLOT. The mode index on the
 * site is the EM label, which depends on the data, so this is not the prior
 * "of mode k" in any label-conditional sense.
 *
 * `priorBinDensity` returns the bin AVERAGE of the density over nb equal bins,
 * the same binning the posterior marginal uses, so the arcsine end-points of
 * eps stay finite.
 */

